#[cfg(test)]
mod tests {
    use super::*;

    fn compiled(file: &str) -> Option<Vec<u32>> {
        let src = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("src/backend/vulkan/engine/shaders")
            .join(file);
        let out = std::env::temp_dir().join(format!("reims_{file}_check.spv"));
        let ok = std::process::Command::new("glslc")
            .arg("-O")
            .arg(&src)
            .arg("-o")
            .arg(&out)
            .status()
            .ok()
            .is_some_and(|s| s.success());
        if !ok {
            eprintln!("SKIP: no glslc, cannot check the embedded SPIR-V against its source");
            return None;
        }
        let bytes = std::fs::read(&out).ok()?;
        Some(
            bytes
                .chunks_exact(4)
                .map(|c| u32::from_le_bytes([c[0], c[1], c[2], c[3]]))
                .collect(),
        )
    }

    #[test]
    fn the_embedded_present_sharp_spirv_matches_its_source() {
        if let Some(fresh) = compiled("present_sharp.vert") {
            assert_eq!(fresh.as_slice(), PRESENT_SHARP_VERT_SPIRV.as_slice(), "recompile present_sharp.vert");
        }
        if let Some(fresh) = compiled("present_sharp.frag") {
            assert_eq!(fresh.as_slice(), PRESENT_SHARP_FRAG_SPIRV.as_slice(), "recompile present_sharp.frag");
        }
    }

    #[test]
    fn the_embedded_present_sharp_spirv_are_spirv_modules() {
        assert_eq!(PRESENT_SHARP_VERT_SPIRV[0], 0x0723_0203);
        assert_eq!(PRESENT_SHARP_FRAG_SPIRV[0], 0x0723_0203);
    }
}
