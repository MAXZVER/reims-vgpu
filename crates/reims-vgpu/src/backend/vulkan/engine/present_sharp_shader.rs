//! TEMP (lab, `REIMS_VGPU_LAB_PRESENT_SHARP=on`): the host window's scaled
//! present through a Catmull-Rom (bicubic) resample instead of
//! `vkCmdBlitImage`'s bilinear filter.
//!
//! # Why
//!
//! A guest mode below the panel's native size — Mish's 4608x1944 on a
//! 5120x2160 screen, for text about 11 % larger — reaches the window through
//! the presenter's aspect-fit, which `vkCmdBlitImage` filters linearly. At
//! 1.11x a bilinear upscale softens every glyph edge; Catmull-Rom keeps them
//! close to the source's contrast, in nine bilinear taps per pixel.
//!
//! # Our own shaders, checked against their source
//!
//! `shaders/present_sharp.vert` / `.frag`, compiled by `glslc -O`, embedded as
//! words like [`super::scatter_shader`] and checked the same way (skipped where
//! `glslc` is absent).

